#!/usr/bin/env python3
"""Generate portable skill copies and native role adapters; no external I/O."""
import argparse
import json
from pathlib import Path
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[2]
MARKER = '<!-- Generated by scripts/agent-coding/sync.py; edit docs/agent-coding. -->'
ROLES = {
    'nextjs-specialist': 'Next.js画面・Server/Client境界・API連携・アクセシビリティの実装担当。',
    'python-ml-iot-specialist': 'FastAPI・MQTT・Device API・前処理・既存モデル推論の実装担当。',
    'senior-code-reviewer': '実装者から独立して差分と証拠を読み、正確性・安全性・保守性をレビューする。',
}


def expected_files():
    result = {}
    for source in sorted((ROOT / 'docs/agent-coding/skills').glob('*/SKILL.md')):
        text = source.read_text()
        # This repository intentionally uses only a small, portable frontmatter subset.
        front = text.split('---', 2)[1].strip().splitlines()
        fields = dict(line.split(': ', 1) for line in front)
        if fields['name'] != source.parent.name or not json.loads(fields['description']):
            raise ValueError(f'Invalid skill metadata: {source}')
        for directory in ('.agents/skills', '.claude/skills', '.github/skills'):
            result[f'{directory}/{source.parent.name}/SKILL.md'] = text + '\n' + MARKER + '\n'
    for name, description in ROLES.items():
        role = f'docs/agent-coding/roles/{name}.md'
        if not (ROOT / role).is_file():
            raise ValueError(f'Missing role: {role}')
        body = f'最初にリポジトリルートの `AGENTS.md` と `{role}` をファイルとして読み、その責務に従ってください。これらはパスの記載だけで自動importされるものではありません。読めない場合は制限を報告してください。\n'
        if name == 'senior-code-reviewer':
            body += '読み取りのみ。ファイル編集・DB更新・外部送信・Merge/Deployは行わず、実際の差分と証拠で指摘してください。\n'
        metadata = f'---\nname: {name}\ndescription: {json.dumps(description, ensure_ascii=False)}\n'
        claude = metadata
        if name == 'senior-code-reviewer':
            claude += 'tools: Read, Grep, Glob\n'
        result[f'.claude/agents/{name}.md'] = claude + '---\n\n' + MARKER + '\n\n' + body
        copilot = metadata
        if name == 'senior-code-reviewer':
            copilot += 'tools: ["read", "search"]\n'
        result[f'.github/agents/{name}.agent.md'] = copilot + '---\n\n' + MARKER + '\n\n' + body
        gemini = metadata + 'kind: local\n'
        if name == 'senior-code-reviewer':
            gemini += 'tools: ["read_file", "grep_search", "glob", "list_directory"]\n'
        result[f'.gemini/agents/{name}.md'] = gemini + '---\n\n' + MARKER + '\n\n' + body
        codex = '# Generated by scripts/agent-coding/sync.py; edit docs/agent-coding.\n'
        for key, value in {'name': name, 'description': description, 'developer_instructions': body}.items():
            codex += f'{key} = {json.dumps(value, ensure_ascii=False)}\n'
        tomllib.loads(codex)
        result[f'.codex/agents/{name}.toml'] = codex
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args()
    expected = expected_files()
    patterns = (
        '.agents/skills/*/SKILL.md', '.claude/skills/*/SKILL.md',
        '.github/skills/*/SKILL.md', '.claude/agents/*.md',
        '.github/agents/*.agent.md', '.gemini/agents/*.md',
        '.codex/agents/*.toml',
    )
    orphans = [
        path.relative_to(ROOT).as_posix()
        for pattern in patterns for path in ROOT.glob(pattern)
        if path.relative_to(ROOT).as_posix() not in expected
        and 'Generated by scripts/agent-coding/sync.py; edit docs/agent-coding.' in path.read_text()
    ]
    if orphans:
        raise ValueError('Stale managed files; review and remove explicitly: ' + ', '.join(orphans))
    changes = []
    for name, text in expected.items():
        target = ROOT / name
        # Refuse symlinks, including parents, to avoid writing outside this checkout.
        if any(p.is_symlink() for p in [target, *target.parents] if p != ROOT.parent):
            raise ValueError(f'Symlink destination refused: {name}')
        old = target.read_text() if target.exists() else None
        if old == text:
            continue
        if old is not None and 'Generated by scripts/agent-coding/sync.py; edit docs/agent-coding.' not in old:
            raise ValueError(f'Unmanaged file; refusing overwrite: {name}')
        changes.append((target, text))
    if args.check:
        for target, _ in changes:
            print(f'MISSING OR STALE: {target.relative_to(ROOT)}')
        if changes:
            return 1
        print(f'PASS: {len(expected)} generated files match their sources; Codex TOML parsed.')
        return 0
    for target, text in changes:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    print(f'Generated {len(changes)} files; {len(expected)} managed files total.')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, KeyError, OSError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        sys.exit(1)
